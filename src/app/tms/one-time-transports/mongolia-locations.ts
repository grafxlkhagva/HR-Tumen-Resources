function normalize(s: string): string {
  return s.trim().toLowerCase().replace(/\s+/g, ' ');
}

const NORM_MAP: Record<string, [number, number]> = {};
for (const key of Object.keys(MN_LOCATIONS)) {
  NORM_MAP[normalize(key)] = MN_LOCATIONS[key];
}

/**
 * Байршлын нэрээс координат хайна. Эхлээд яг таарахыг, дараа нь
 * хоёр чиглэлд агуулагдах (contains) таарцыг шалгана.
 * Олдохгүй бол null.
 */
export function findCoords(name?: string | null): [number, number] | null {
  if (!name) return null;
  const n = normalize(name);
  if (!n) return null;
  if (NORM_MAP[n]) return NORM_MAP[n];
  for (const key of Object.keys(NORM_MAP)) {
    if (key.length >= 3 && (n.includes(key) || key.includes(n))) {
      return NORM_MAP[key];
    }
  }
  return null;
}

/**
 * Хоёр цэгийн хоорондох агаарын (их тойргийн) зайг км-ээр буцаана.
 * Бодит замын зай биш — зөвхөн UI-д баримжаа болгон харуулна.
 */
export function haversineKm(a: [number, number], b: [number, number]): number {
  const R = 6371;
  const toRad = (x: number) => (x * Math.PI) / 180;
  const dLat = toRad(b[0] - a[0]);
  const dLng = toRad(b[1] - a[1]);
  const lat1 = toRad(a[0]);
  const lat2 = toRad(b[0]);
  const h =
    Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}
